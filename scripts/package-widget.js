import { mkdir, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const cli = path.join(root, 'node_modules/icuewidget-cli/node-bin/icuewidget.js');
await mkdir(path.join(root, 'dist'), { recursive: true });
const result = spawnSync(process.execPath, [cli, 'package', path.join(root, 'widget'), '-o', path.join(root, 'dist', 'XeneonTube.icuewidget')], { cwd: root, stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status || 1);
// Remove only obsolete outputs generated by the previous variant packager.
for (const layout of ['compact', 'medium', 'wide']) {
  await rm(path.join(root, 'dist', `XeneonTube-${layout}.icuewidget`), { force: true });
  await rm(path.join(root, 'build', `widget-${layout}`), { recursive: true, force: true });
}
